const assert=require('node:assert/strict');
const H=require('../site/assets/hazard-core.js');
const land=require('../site/data/simulation_land.json');
const coasts=require('../site/data/jma_tsunami_coast.json');
const sea={lat:32.5,lon:134.3,magnitude:7.6,depthKm:25};
assert.equal(H.tsunamiLevel(.199),null);
assert.equal(H.tsunamiLevel(.2).id,'advisory');
assert.equal(H.tsunamiLevel(1).id,'advisory');
assert.equal(H.tsunamiLevel(1.01).id,'warning');
assert.equal(H.tsunamiLevel(3).id,'warning');
assert.equal(H.tsunamiLevel(3.01).id,'major');
const result=H.tsunami(sea,land,coasts);
assert.equal(result.status,'warning');
assert.ok(result.features.some(f=>f.properties.name==='고치현'));
assert.ok(result.features.some(f=>f.properties.rank===3));
assert.ok(result.features.some(f=>f.properties.rank===2));
assert.equal(H.tsunami({...sea,magnitude:6.4},land,coasts).status,'below');
assert.equal(H.tsunami({...sea,depthKm:101},land,coasts).status,'below');
assert.equal(H.tsunami({...sea,lat:35.7,lon:129.35},land,coasts).status,'land');
assert.equal(H.tsunami({...sea,lat:10},land,coasts).status,'outside');
assert.equal(H.tsunami(sea,land,coasts,31).status,'invalid_height');
assert.equal(H.tsunami(sea,land,coasts,0).status,'no_coast');
const smallWave=H.tsunami(sea,land,coasts,1);
assert.equal(smallWave.status,'warning');
assert.ok(smallWave.features.every(f=>f.properties.rank===1));
assert.ok(H.tsunami(sea,land,coasts,10).features.some(f=>f.properties.rank===3));
const barrier={type:'FeatureCollection',features:[{type:'Feature',geometry:{type:'Polygon',coordinates:[[[127,24],[128,24],[128,49],[127,49],[127,24]]]},properties:{}}]};
const blocked=H.waterDistances({lat:35,lon:125},barrier);
const otherSide=Math.round((35-25)/.25)*121+Math.round((130-120)/.25);
assert.equal(blocked.dist[otherSide],Infinity,'water route cannot go through a land barrier');
const regions=[{name:'근거리',lat:35.03,lon:135},{name:'동쪽',lat:35,lon:135.6},{name:'서쪽',lat:35,lon:134.4}];
const eruption=H.volcano(35,135,4,'E',regions);
assert.equal(eruption.radius,30);
assert.ok(eruption.features.some(f=>f.geometry.type==='Point'));
assert.equal(eruption.features.filter(f=>f.geometry.type==='Polygon').length,2);
assert.deepEqual(eruption.nearby,['근거리']);
assert.ok(eruption.ash.includes('동쪽'));
assert.ok(!eruption.ash.includes('서쪽'));
assert.ok(H.volcano(35,135,4,'W',regions).ash.includes('서쪽'));
assert.equal(H.volcano(35,135,9),null);
assert.equal(H.volcano(35,135,4,'BAD'),null);
const now=Date.parse('2026-11-25T00:00:00Z');
const sample=coasts.features.find(f=>f.properties.name==='高知県');
const event={issuedAt:new Date(now-60000).toISOString(),cancelled:false,areas:[{name:sample.properties.name,level:'지진해일 경보'}]};
const feed={state:'ok',items:[event]};
assert.equal(H.realTsunami(feed,coasts,now).length,1);
assert.equal(H.realTsunami({...feed,state:'error'},coasts,now).length,0);
assert.equal(H.realTsunami({state:'ok',items:[{...event,cancelled:true}]},coasts,now).length,0);
assert.equal(H.realTsunami(feed,coasts,now+86400000).length,0);
assert.equal(H.realTsunami({state:'ok',items:[event,{...event,issuedAt:new Date(now).toISOString(),cancelled:true}]},coasts,now).length,0);
assert.equal(H.realTsunami({state:'ok',items:[{...event,areas:[{name:'모르는 구역',level:'지진해일 경보'}]}]},coasts,now).length,0);
console.log('Hazard simulation and announcement mapping tests passed');
