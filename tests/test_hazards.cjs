const assert=require('node:assert/strict');
const H=require('../site/assets/hazard-core.js');
const land=require('../site/data/base_geometry.json');
const coasts=require('../site/data/jma_tsunami_coast.json');
const sea={lat:32.5,lon:134.3,magnitude:7.6,depthKm:25};
assert.equal(H.tsunami(sea,land,coasts).status,'warning');
assert.ok(H.tsunami(sea,land,coasts).features.some(f=>f.properties.name==='고치현'));
assert.equal(H.tsunami({...sea,magnitude:6.9},land,coasts).status,'below');
assert.equal(H.tsunami({...sea,depthKm:71},land,coasts).status,'below');
assert.equal(H.tsunami({...sea,lat:35.7,lon:129.35},land,coasts).status,'land');
assert.equal(H.tsunami({...sea,lat:10},land,coasts).status,'outside');
assert.equal(H.volcano(35,129,4).radius,40);
assert.equal(H.volcano(35,129,4).features[0].geometry.type,'Point');
assert.equal(H.volcano(35,129,9),null);
const now=Date.parse('2026-11-25T00:00:00Z');
const sample=coasts.features.find(f=>f.properties.name==='高知県');
const event={issuedAt:new Date(now-60000).toISOString(),cancelled:false,areas:[{name:sample.properties.name,level:'지진해일 경보'}]};
const feed={state:'ok',items:[event]};
assert.equal(H.realTsunami(feed,coasts,now).length,1);
assert.equal(H.realTsunami({...feed,state:'error'},coasts,now).length,0);
assert.equal(H.realTsunami({state:'ok',items:[{...event,cancelled:true}]},coasts,now).length,0);
assert.equal(H.realTsunami(feed,coasts,now+86400000).length,0);
assert.equal(H.realTsunami({state:'ok',items:[event,{...event,issuedAt:new Date(now).toISOString(),cancelled:true}]},coasts,now).length,0);
assert.equal(H.realTsunami({state:'ok',items:[{...event,areas:[{name:'모르는 구역',level:'지진해일 경보'}]}]},coasts,now).length,0);
console.log('Hazard simulation and announcement mapping tests passed');
